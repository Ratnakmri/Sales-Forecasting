import numpy as np

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error
)


def evaluate_model(actual, predicted):

    mae = mean_absolute_error(
        actual,
        predicted
    )

    rmse = np.sqrt(
        mean_squared_error(
            actual,
            predicted
        )
    )

    return mae, rmse